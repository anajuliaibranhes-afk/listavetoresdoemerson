public class ex02 {

	 public static void main(String[] args) {
	        int[] vetor = {2, 4, 6, 8, 10};
	        int soma = 0;

	        for (int i = 0; i < vetor.length; i++) {
	            soma += vetor[i];
	        }

	        System.out.println("Soma: " + soma);
	    }
	}

